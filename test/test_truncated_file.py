import oead


def test_truncate_str_table():
    data = bytes([
        0x59, 0x42, 0x0A, 0x00, 0x1C, 0x00, 0x00, 0x00, 0x2C, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 
        0xC1, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0xA0, 0x00, 0x00, 0x00, 0x00, 0xC2, 0x01, 0x00, 0x00, 
        0x0C, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x66, 0x6F, 0x6F, 0x00, 0xC2, 0x01, 0x00, 0x00, 
        0x0C, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x62, 0x61, 0x72, 0x00,
    ])
    assert oead.byml.from_binary(data) == oead.byml.Hash({ "foo" : "bar" })
    parsed = oead.byml.from_binary(data[:-2])
    assert parsed.get("foo") == "ba"